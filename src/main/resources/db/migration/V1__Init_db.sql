CREATE TABLE connection
(
    id     BIGINT GENERATED BY DEFAULT AS IDENTITY NOT NULL,
    child  BIGINT                                  NOT NULL,
    father BIGINT,
    mother BIGINT,
    CONSTRAINT pk_connection PRIMARY KEY (id)
);

CREATE TABLE individual
(
    id         BIGINT GENERATED BY DEFAULT AS IDENTITY NOT NULL,
    real_id    VARCHAR(255),
    name       VARCHAR(255),
    sex        VARCHAR(255),
    birth_date date,
    death_date date,
    CONSTRAINT pk_individual PRIMARY KEY (id)
);

